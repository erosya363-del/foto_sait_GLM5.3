import { chromium } from "playwright";
const BASE = process.env.E2E_BASE || "http://localhost:3100";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
page.on("pageerror", (e) => console.log("[pageerror]", String(e).slice(0, 200)));
await page.goto(BASE, { waitUntil: "networkidle" });
await page.waitForTimeout(1000);

await page.locator('nav.pill-nav button:has-text("Загрузка")').click();
await page.waitForTimeout(900);
await page.locator('[data-upload-sheet] select').first().selectOption({ index: 1 });
await page.waitForTimeout(250);
await page.locator('[data-upload-sheet] select').nth(1).selectOption({ index: 1 }).catch(() => {});
await page.waitForTimeout(250);
await page.locator('[data-upload-sheet] button:has-text("Далее")').click();
await page.waitForTimeout(400);
await page.locator('[data-upload-sheet] button:has-text("Далее")').click();
await page.waitForTimeout(400);
console.log("step3:", await page.evaluate(() => Boolean(document.querySelector('[data-upload-sheet] input[type="file"]'))));
await page.locator('[aria-label="Закрыть загрузку"]').click();
await page.waitForTimeout(400);
console.log("confirm:", await page.evaluate(() => Boolean(document.querySelector("[data-upload-confirm]"))));
await page.locator('[data-upload-confirm] button:has-text("Закрыть")').click();
await page.waitForTimeout(700);
console.log("closed:", await page.evaluate(() => !document.querySelector("[data-upload-sheet]")));
await page.locator('nav.pill-nav button:has-text("Загрузка")').click();
await page.waitForTimeout(900);
console.log("reopen:", await page.evaluate(() => Boolean(document.querySelector("[data-upload-sheet]"))));
console.log("selects:", await page.locator('[data-upload-sheet] select').count());
await browser.close();
